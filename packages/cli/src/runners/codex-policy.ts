/**
 * Step policy → Codex. The Claude side of this lives in `tools.ts`; this is the same server grants
 * and approval categories expressed the way Codex understands them.
 *
 * Two mechanisms:
 *  - an **execpolicy**: Starlark `.rules` files holding `prefix_rule(pattern=[…], decision=…)`.
 *    Codex's three decisions (`allow`, `prompt`, `forbidden`) line up with what a step actually
 *    means, so unlike the Claude mapping — which can only allow or block — a category that needs
 *    approval becomes a real approval request.
 *  - the **sandbox**, which stays the outer guard: read-only for steps that only look.
 *
 * The approval categories come from `APPROVAL_RULES` so Claude and Codex cannot drift apart.
 */
import { APPROVAL_RULES } from "./tools.js";

/** A single execpolicy decision. Codex rejects anything else at parse time. */
export type CodexDecision = "allow" | "prompt" | "forbidden";

/** Command words only: no shell metacharacters, no globs, nothing that could escape the list. */
const TOKEN = /^[A-Za-z0-9_.@/:=+,-]{1,64}$/;

/** `Bash(git push:*)` → `["git","push"]`; a non-Bash rule (WebFetch) has no shell form → null. */
export function tokensFromClaudeRule(rule: string): string[] | null {
  const m = /^Bash\((.*)\)$/.exec(rule);
  if (!m) return null;
  return tokenize(m[1]!.replace(/:\*$/, ""));
}

/** `bash:npm run *` → `["npm","run"]`. A trailing glob just means "and any arguments". */
export function tokenize(command: string): string[] | null {
  const parts = command.trim().replace(/\s+/g, " ").split(" ").filter((p) => p && p !== "*");
  if (!parts.length) return null;
  return parts.every((p) => TOKEN.test(p)) ? parts : null;
}

const starlarkList = (tokens: string[]) => `[${tokens.map((t) => JSON.stringify(t)).join(", ")}]`;

export interface CodexPolicy {
  /** The `.rules` file contents. */
  rules: string;
  /** Grants that have no shell form, so the sandbox and Codex's own tools govern them. */
  dropped: string[];
}

/**
 * Builds the execpolicy for one step.
 *
 * A longer prefix wins over a shorter one regardless of the order the rules appear in, so a broad
 * allow (`git`) and a narrow `prompt` (`git push`) coexist: `git status` is allowed outright and
 * `git push` still asks. Verified against `codex execpolicy check` in the tests, both orderings.
 */
export function buildCodexPolicy(allowed: string[], requiresApproval: string[]): CodexPolicy {
  const lines: string[] = [
    "# Generated by agnt0 for a single step. Do not edit; it is rewritten every step.",
    "# prefix_rule matches the leading words of a command; the longest match wins.",
  ];
  const dropped: string[] = [];
  const seen = new Set<string>();

  const rule = (tokens: string[], decision: CodexDecision) => {
    const key = `${decision}:${tokens.join(" ")}`;
    if (seen.has(key)) return;
    seen.add(key);
    const arg = decision === "allow" ? "" : `, decision=${JSON.stringify(decision)}`;
    lines.push(`prefix_rule(pattern=${starlarkList(tokens)}${arg})`);
  };

  for (const raw of allowed) {
    const t = raw.trim();
    if (!t) continue;
    if (t.toLowerCase().startsWith("bash:")) {
      const tokens = tokenize(t.slice(5));
      if (tokens) rule(tokens, "allow");
      else dropped.push(t);
      continue;
    }
    // Everything else is one of Codex's own tools (read, write, search), not a shell command.
    dropped.push(t);
  }

  // A category that needs approval is a longer prefix than the grant it narrows, so it wins.
  const needs = new Set(requiresApproval.map((c) => c.trim().toLowerCase()).filter(Boolean));
  for (const cat of needs) {
    for (const r of APPROVAL_RULES[cat] ?? []) {
      const tokens = tokensFromClaudeRule(r);
      if (tokens) rule(tokens, "prompt");
      else dropped.push(r);
    }
  }

  return { rules: `${lines.join("\n")}\n`, dropped };
}
